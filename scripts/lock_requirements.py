"""Record the full pip-download closure with SHA-256, without importing packages."""
import argparse
import email
import hashlib
from pathlib import Path
import tarfile
import zipfile


def lock_downloads(directory):
    result = {}
    for path in sorted(Path(directory).iterdir()):
        if path.suffix == ".whl":
            with zipfile.ZipFile(path) as archive:
                name = next(name for name in archive.namelist() if name.endswith(".dist-info/METADATA"))
                metadata = email.message_from_bytes(archive.read(name))
        elif path.name.endswith(".tar.gz"):
            with tarfile.open(path) as archive:
                name = next(name for name in archive.getnames() if name.endswith("/PKG-INFO"))
                metadata = email.message_from_bytes(archive.extractfile(name).read())
        else:
            raise ValueError(f"Unexpected download: {path.name}")
        key = metadata["Name"].lower().replace("_", "-")
        if key in result:
            raise ValueError(f"Multiple distributions for {key}; use an empty download directory")
        result[key] = (f"{metadata['Name']}=={metadata['Version']} "
                       f"--hash=sha256:{hashlib.sha256(path.read_bytes()).hexdigest()}\n")
    if not result:
        raise ValueError("Download directory is empty")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("download_directory")
    parser.add_argument("output")
    parser.add_argument("--bootstrap-output")
    args = parser.parse_args()
    packages = lock_downloads(args.download_directory)
    header = ("# Linux x86_64 / CPython 3.10 / CPU. Generated by scripts/lock_requirements.py.\n"
              "# Install the pinned build backend first; use --no-build-isolation.\n"
              "--extra-index-url https://download.pytorch.org/whl/cpu\n\n")
    Path(args.output).write_text(header + "".join(packages[name] for name in sorted(packages)), encoding="utf-8")
    if args.bootstrap_output:
        Path(args.bootstrap_output).write_text(
            "# Pinned source-build backend; install before runtime/training lock.\n" + packages["setuptools"],
            encoding="utf-8",
        )


if __name__ == "__main__":
    main()
